export type MessageKey = keyof typeof messages.en;

export function translate(
  locale: 'en' | 'ar',
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const table = messages[locale] as Record<string, string>;
  const fallback = messages.en[key];
  const template = table[key] ?? fallback;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] === undefined ? `{${name}}` : String(vars[name]),
  );
}

/** Arabic plural buckets used by the interface. English uses one/other. */
export function pluralPhrase(
  locale: 'en' | 'ar',
  base: 'nav.reviewCount',
  count: number,
): string {
  if (locale === 'en') {
    const key = count === 1 ? 'nav.reviewCount.one' : 'nav.reviewCount.other';
    return translate('en', key, { count });
  }
  const n = Math.abs(count);
  const form =
    n === 0 ? 'other' : n === 1 ? 'one' : n === 2 ? 'two' : n >= 3 && n <= 10 ? 'few' : 'many';
  const key = `nav.reviewCount.${form}` as MessageKey;
  return translate('ar', key, { count });
}
